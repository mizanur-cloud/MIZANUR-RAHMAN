import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import {
  AlignmentType,
  BorderStyle,
  Document,
  ImageRun,
  Packer,
  Paragraph,
  ShadingType,
  Table,
  TableCell,
  TableRow,
  TextRun,
  WidthType,
} from 'docx';
import { saveAs } from 'file-saver';
import { ProxyPlanResult } from './proxyGenerator';
import { SchoolSettings, Teacher } from '../types';
import { loadSchoolLogoBytes, loadSchoolLogoDataUrl } from './logoAsset';

const BORDER_STYLE = {
  style: BorderStyle.SINGLE,
  size: 1,
  color: 'CCCCCC',
};

const CELL_BORDERS = {
  top: BORDER_STYLE,
  bottom: BORDER_STYLE,
  left: BORDER_STYLE,
  right: BORDER_STYLE,
};

// 1. Export Proxy Routine in PDF
export async function exportProxyPdf(plan: ProxyPlanResult, settings: SchoolSettings, teachers: Teacher[]) {
  const logoDataUrl = await loadSchoolLogoDataUrl();
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  if (logoDataUrl) {
    doc.addImage(logoDataUrl, 'JPEG', 14, 8, 17, 17);
  }

  // Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(30, 58, 138); // Navy blue
  doc.text(settings.schoolName.toUpperCase(), pageWidth / 2, 14, { align: 'center' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(71, 85, 105);
  doc.text(`Academic Year: ${settings.academicYear} • ${settings.schoolAddress}`, pageWidth / 2, 20, {
    align: 'center',
  });

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(185, 28, 28); // Crimson
  doc.text('DAILY PROXY & SUBSTITUTE CLASS ROUTINE', pageWidth / 2, 26, { align: 'center' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(15, 23, 42);
  const teacherMap = new Map(teachers.map(t => [t.id, t]));
  const absentNames = plan.absentTeacherIds
    .map(id => teacherMap.get(id)?.name || id)
    .join(', ');

  doc.text(`Day: ${plan.day}   |   Absent Faculty: ${absentNames || 'None'}`, 14, 33);
  doc.text(`Total Affected Classes: ${plan.totalAbsentClasses}   |   Assigned: ${plan.assignedCount}   |   Unassigned: ${plan.unassignedCount}`, 14, 38);

  doc.setDrawColor(203, 213, 225);
  doc.line(14, 41, pageWidth - 14, 41);

  // Table
  const head = [['Period', 'Time', 'Class & Sec', 'Subject', 'Absent Teacher', 'Assigned Proxy Teacher', 'Match Note']];
  const body = plan.assignments.map(a => [
    a.periodLabel,
    a.periodTime,
    `${a.className} (${a.sectionName})`,
    a.subjectName,
    a.absentTeacherName,
    a.substituteTeacherName || '— Unassigned —',
    a.matchReason,
  ]);

  autoTable(doc, {
    startY: 44,
    head: head,
    body: body,
    theme: 'grid',
    headStyles: {
      fillColor: [30, 58, 138],
      textColor: 255,
      fontStyle: 'bold',
      fontSize: 8.5,
    },
    bodyStyles: {
      fontSize: 8,
      cellPadding: 3,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
  });

  // Principal Signature Block at bottom
  const finalY = (doc as any).lastAutoTable?.finalY || 180;
  if (finalY < pageHeight - 35) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(51, 65, 85);

    doc.text('Prepared By:', 20, finalY + 25);
    doc.text('Routine Coordinator', 20, finalY + 30);

    doc.text('Approved By:', pageWidth - 60, finalY + 25);
    doc.text(`${settings.principalName || 'Principal'}`, pageWidth - 60, finalY + 30);
    doc.text(settings.schoolName, pageWidth - 60, finalY + 34);
  }

  // Footer
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text('Generated by Smart Routine Management System • Official Notice', 14, pageHeight - 8);

  doc.save(`${settings.schoolName.replace(/\s+/g, '_')}_Proxy_Routine_${plan.day}.pdf`);
}

// 2. Export Proxy Routine in Word (.docx)
export async function exportProxyDocx(plan: ProxyPlanResult, settings: SchoolSettings, teachers: Teacher[]) {
  const logoBytes = await loadSchoolLogoBytes();
  const teacherMap = new Map(teachers.map(t => [t.id, t]));
  const absentNames = plan.absentTeacherIds
    .map(id => teacherMap.get(id)?.name || id)
    .join(', ');

  const headerParagraphs: Paragraph[] = [
    ...(logoBytes
      ? [
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { after: 50 },
            children: [
              new ImageRun({
                type: 'jpg',
                data: logoBytes,
                transformation: { width: 52, height: 52 },
                altText: {
                  name: 'SchoolLogo',
                  description: 'Icon Dreams School & College Logo',
                  title: 'Icon Dreams School & College Logo',
                },
              }),
            ],
          }),
        ]
      : []),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 60 },
      children: [
        new TextRun({
          text: settings.schoolName.toUpperCase(),
          bold: true,
          size: 30,
          color: '1E3A8A',
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 60 },
      children: [
        new TextRun({
          text: `ACADEMIC YEAR: ${settings.academicYear} • ${settings.schoolAddress}`,
          bold: false,
          size: 18,
          color: '475569',
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 100 },
      children: [
        new TextRun({
          text: `DAILY PROXY & SUBSTITUTE CLASS ROUTINE (${plan.day.toUpperCase()})`,
          bold: true,
          size: 24,
          color: 'B91C1C',
        }),
      ],
    }),
    new Paragraph({
      spacing: { after: 120 },
      children: [
        new TextRun({ text: `Day: `, bold: true, size: 20 }),
        new TextRun({ text: `${plan.day}  |  `, size: 20 }),
        new TextRun({ text: `Absent Teacher(s): `, bold: true, size: 20 }),
        new TextRun({ text: `${absentNames || 'None'}  |  `, size: 20 }),
        new TextRun({ text: `Assigned: `, bold: true, size: 20 }),
        new TextRun({ text: `${plan.assignedCount}/${plan.totalAbsentClasses} classes`, size: 20 }),
      ],
    }),
  ];

  const headerRow = new TableRow({
    tableHeader: true,
    children: [
      new TableCell({
        width: { size: 1200, type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: '1E3A8A' },
        borders: CELL_BORDERS,
        children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: 'PERIOD', bold: true, color: 'FFFFFF', size: 16 })] })],
      }),
      new TableCell({
        width: { size: 1400, type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: '1E3A8A' },
        borders: CELL_BORDERS,
        children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: 'TIME', bold: true, color: 'FFFFFF', size: 16 })] })],
      }),
      new TableCell({
        width: { size: 1500, type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: '1E3A8A' },
        borders: CELL_BORDERS,
        children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: 'CLASS & SEC', bold: true, color: 'FFFFFF', size: 16 })] })],
      }),
      new TableCell({
        width: { size: 1800, type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: '1E3A8A' },
        borders: CELL_BORDERS,
        children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: 'SUBJECT', bold: true, color: 'FFFFFF', size: 16 })] })],
      }),
      new TableCell({
        width: { size: 1800, type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: '1E3A8A' },
        borders: CELL_BORDERS,
        children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: 'ABSENT TEACHER', bold: true, color: 'FFFFFF', size: 16 })] })],
      }),
      new TableCell({
        width: { size: 2000, type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: '1E3A8A' },
        borders: CELL_BORDERS,
        children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: 'PROXY TEACHER', bold: true, color: 'FFFFFF', size: 16 })] })],
      }),
    ],
  });

  const dataRows = plan.assignments.map((a, idx) => {
    const rowBg = idx % 2 === 1 ? 'F8FAFC' : 'FFFFFF';
    return new TableRow({
      children: [
        new TableCell({
          width: { size: 1200, type: WidthType.DXA },
          shading: { type: ShadingType.CLEAR, fill: rowBg },
          borders: CELL_BORDERS,
          children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: a.periodLabel, bold: true, size: 16 })] })],
        }),
        new TableCell({
          width: { size: 1400, type: WidthType.DXA },
          shading: { type: ShadingType.CLEAR, fill: rowBg },
          borders: CELL_BORDERS,
          children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: a.periodTime, size: 15 })] })],
        }),
        new TableCell({
          width: { size: 1500, type: WidthType.DXA },
          shading: { type: ShadingType.CLEAR, fill: rowBg },
          borders: CELL_BORDERS,
          children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: `${a.className} (${a.sectionName})`, bold: true, size: 16 })] })],
        }),
        new TableCell({
          width: { size: 1800, type: WidthType.DXA },
          shading: { type: ShadingType.CLEAR, fill: rowBg },
          borders: CELL_BORDERS,
          children: [new Paragraph({ alignment: AlignmentType.LEFT, children: [new TextRun({ text: a.subjectName, size: 16 })] })],
        }),
        new TableCell({
          width: { size: 1800, type: WidthType.DXA },
          shading: { type: ShadingType.CLEAR, fill: rowBg },
          borders: CELL_BORDERS,
          children: [new Paragraph({ alignment: AlignmentType.LEFT, children: [new TextRun({ text: a.absentTeacherName, size: 16, color: '991B1B' })] })],
        }),
        new TableCell({
          width: { size: 2000, type: WidthType.DXA },
          shading: { type: ShadingType.CLEAR, fill: rowBg },
          borders: CELL_BORDERS,
          children: [
            new Paragraph({
              alignment: AlignmentType.LEFT,
              children: [
                new TextRun({ text: a.substituteTeacherName || 'Unassigned', bold: true, size: 16, color: '1E3A8A' }),
              ],
            }),
            new Paragraph({
              alignment: AlignmentType.LEFT,
              children: [new TextRun({ text: `(${a.matchReason})`, size: 13, color: '64748B' })],
            }),
          ],
        }),
      ],
    });
  });

  const table = new Table({
    width: { size: 9700, type: WidthType.DXA },
    rows: [headerRow, ...dataRows],
  });

  const doc = new Document({
    sections: [{ children: [...headerParagraphs, table] }],
  });

  const blob = await Packer.toBlob(doc);
  saveAs(blob, `${settings.schoolName.replace(/\s+/g, '_')}_Proxy_Routine_${plan.day}.docx`);
}
